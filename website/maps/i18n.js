export const LANGUAGES = ["en", ...Object.keys(STRINGS)]

function preferred() {
  const list = typeof navigator === "undefined" ? [] : navigator.languages?.length ? navigator.languages : [navigator.language]
  for (const tag of list) {
    const code = String(tag || "").slice(0, 2).toLowerCase()
    if (LANGUAGES.includes(code)) return { code, tag }
  }
  return { code: "en", tag: "en" }
}

const chosen = preferred()

export function language() {
  return chosen.code
}

// The browser's own tag when it names the chosen language (en-GB, pt-BR), so numbers and times follow the region.
export function locale() {
  return chosen.tag
}

export function t(key, vars) {
  let text = STRINGS[chosen.code]?.[key] || key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value))
  }
  return text
}

export function localize(root = document) {
  document.documentElement.lang = chosen.code
  for (const el of root.querySelectorAll("[data-i18n]")) {
    el.dataset.i18n ||= el.textContent.trim()
    el.textContent = t(el.dataset.i18n)
  }
  for (const el of root.querySelectorAll("[data-i18n-label]")) {
    el.dataset.i18nLabel ||= el.getAttribute("aria-label") || ""
    el.setAttribute("aria-label", t(el.dataset.i18nLabel))
  }
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) {
    el.dataset.i18nPlaceholder ||= el.getAttribute("placeholder") || ""
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder))
  }
}
